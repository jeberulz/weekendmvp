#!/usr/bin/env node
/**
 * Regression gate for the idea corpus baseline.
 *
 * Holds three already-shipped pages as the quality bar the idea engine has to
 * clear. The bar is "as complete as pages we already published", fixed in
 * engine/eval/gold.json before the Ideabrowser subscription lapses — it cannot
 * be re-derived from MCP later.
 *
 * Usage:
 *   npm run engine:eval           # diff gold slugs against the recorded bar
 *   npm run engine:eval -- --write  # re-record the bar from the auditor
 *
 * Exit 0 when no gold page regressed. Exit 1 on any regression or drift.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { auditIdeaMdx } from './audit-idea-mdx.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ideasDir = path.join(root, 'content', 'ideas');
const goldPath = path.join(root, 'engine', 'eval', 'gold.json');

/** Counts may grow, never shrink. */
const METRICS = ['wordCount', 'competitorMentions', 'sourceLinkCount', 'howToStepCount'];

const GOLD_SLUGS = [
  'ai-rfp-response-assistant',
  'ai-code-reviewer',
  'ai-landing-page-generator-ecommerce',
];

/** Audit one gold slug into a GoldEntry. */
function measure(slug) {
  const file = path.join(ideasDir, `${slug}.mdx`);
  if (!fs.existsSync(file)) throw new Error(`gold page missing: content/ideas/${slug}.mdx`);
  const result = auditIdeaMdx(slug, fs.readFileSync(file, 'utf8'));
  return {
    slug,
    ...Object.fromEntries(METRICS.map((m) => [m, result.metrics[m]])),
    // The checks this page passes today. A check that flips pass → fail is a
    // regression even when every count held.
    passing: result.checks.filter((c) => c.ok).map((c) => c.id).sort(),
  };
}

function write() {
  const payload = {
    generatedAt: new Date().toISOString(),
    note: 'Generated by `npm run engine:eval -- --write` from scripts/audit-idea-mdx.mjs. '
      + 'Never hand-edited. Counts are a floor, not a target.',
    entries: GOLD_SLUGS.map(measure),
  };
  fs.mkdirSync(path.dirname(goldPath), { recursive: true });
  fs.writeFileSync(goldPath, `${JSON.stringify(payload, null, 2)}\n`);
  console.log(`wrote ${path.relative(root, goldPath)}: ${payload.entries.length} gold page(s)`);
}

function compare() {
  if (!fs.existsSync(goldPath)) {
    console.error('no engine/eval/gold.json — run `npm run engine:eval -- --write` first');
    return 1;
  }
  const gold = JSON.parse(fs.readFileSync(goldPath, 'utf8'));
  const problems = [];

  for (const expected of gold.entries) {
    const actual = measure(expected.slug);
    const mine = [];
    for (const metric of METRICS) {
      if (actual[metric] < expected[metric]) {
        mine.push(`${expected.slug}: ${metric} fell ${expected[metric]} → ${actual[metric]}`);
      }
    }
    for (const id of expected.passing.filter((c) => !actual.passing.includes(c))) {
      mine.push(`${expected.slug}: check "${id}" no longer passes`);
    }
    problems.push(...mine);

    console.log(`${(mine.length ? 'REGRESSED' : 'ok').padEnd(9)} ${expected.slug}  ` +
      METRICS.map((m) => `${m} ${actual[m]}/${expected[m]}`).join('  '));
  }

  const missing = GOLD_SLUGS.filter((s) => !gold.entries.some((e) => e.slug === s));
  for (const slug of missing) problems.push(`${slug}: named as gold but absent from gold.json`);

  console.log(`\nengine:eval — ${gold.entries.length} gold page(s), ${problems.length} problem(s)`);
  for (const p of problems) console.error(`   ✗ ${p}`);
  return problems.length ? 1 : 0;
}

function main() {
  if (process.argv.includes('--write')) {
    write();
    return;
  }
  process.exitCode = compare();
}

main();
